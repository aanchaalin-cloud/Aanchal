type CacheEntry = {
  cities: string[];
  pincodeMap: Record<string, string[]>;
};

const cache: Record<string, CacheEntry> = {};

export function getCitiesForState(state: string): CacheEntry {
  if (cache[state]) return cache[state];

  const cityPincodes = STATE_DATA[state] || {};
  const cities = Object.keys(cityPincodes).sort();
  const pincodeMap: Record<string, string[]> = {};

  for (const [city, pincodes] of Object.entries(cityPincodes)) {
    for (const pin of pincodes) {
      if (!pincodeMap[pin]) pincodeMap[pin] = [];
      pincodeMap[pin].push(city);
    }
  }

  cache[state] = { cities, pincodeMap };
  return cache[state];
}

export function validatePincode(
  state: string,
  city: string,
  pincode: string,
  pincodeMap: Record<string, string[]>,
): { valid: boolean; error?: string } {
  if (!pincode || !/^\d{6}$/.test(pincode)) {
    return { valid: false, error: "Pincode must be 6 digits" };
  }

  if (Object.keys(pincodeMap).length === 0) {
    return { valid: true };
  }

  const citiesForPin = pincodeMap[pincode];
  if (!citiesForPin) {
    const firstDigit = parseInt(pincode[0]);
    const stateDigits = getStateFirstDigit(state);
    if (stateDigits.length > 0 && !stateDigits.includes(firstDigit)) {
      return { valid: false, error: `Pincode ${pincode} does not appear to be in ${state}` };
    }
    return { valid: true };
  }

  const matchesCity = citiesForPin.some(
    (c) => c.toLowerCase() === city.toLowerCase(),
  );

  if (!matchesCity) {
    return {
      valid: false,
      error: `Pincode ${pincode} belongs to ${citiesForPin[0]}, not ${city}. Please select ${citiesForPin[0]} or choose a different pincode.`,
    };
  }

  return { valid: true };
}

